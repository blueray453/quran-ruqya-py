#!/usr/bin/env python3
"""Stage 6: generate docs/QUESTIONS.md (from the query scripts themselves) and docs/examples/.

docs/QUESTIONS.md maps every question to the script that answers it, taken from each queries/qNN_*.py
(QUESTION, KIND, LIMITS, ARGS, DEMO), so the document cannot drift from the code.
docs/examples/ holds ONE illustrative record of each special case; the COMPLETE lists are in output/analysis/source-lists/.
Usage: python3 pipeline/06_docs.py
"""
import glob
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..'))
sys.path.insert(0, os.path.join(HERE, 'lib'))
import grammar_data as G

KIND_TEXT = {'original': 'stored annotation (from the Treebank)',
             'derived': 'derived here by a documented rule',
             'partial': 'only partly answered by the data',
             'research': 'computed over the whole corpus'}


def load_queries():
    qs = []
    sys.path.insert(0, os.path.join(ROOT, 'queries'))
    for f in sorted(glob.glob(os.path.join(ROOT, 'queries', 'q[0-9][0-9]_*.py'))):
        name = os.path.basename(f)[:-3]
        spec = importlib.util.spec_from_file_location(name, f)
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        qs.append((name, m))
    return qs


def command(name, m):
    parts = ['python3 queries/%s.py' % name]
    for arg, _, default in m.ARGS:
        if arg in m.DEMO:
            parts.append(str(m.DEMO[arg]) if default is ... else '--%s %s' % (arg, m.DEMO[arg]))
    return ' '.join(parts)


def questions_md(qs):
    L = ['# Questions this dataset can answer', '',
         'Generated by `pipeline/06_docs.py` from the scripts in `queries/` (one script per question). Each script reads only the two JSON layers in',
         '`output/` and prints its answer as JSON. `python3 queries/_self_test.py` runs every script on a known example and checks the answer.', '',
         '| Source | Meaning |', '|---|---|']
    L += ['| %s | %s |' % (k, v) for k, v in KIND_TEXT.items()]
    L += ['', '| # | Question | Script | Source | Example |', '|---|---|---|---|---|']
    for name, m in qs:
        L.append('| %s | %s | `%s.py` | %s | `%s` |' % (name[1:3], m.QUESTION, name, m.KIND, command(name, m)))
    L += ['', '## What each answer can and cannot tell you', '']
    for name, m in qs:
        L += ['**%s** (`%s.py`): %s' % (name[:3].upper(), name, m.LIMITS), '']
    L += ['## What the data cannot answer', '',
          '* *Why* a case applies: the source has case, relation and head but no explanation text. Q08 applies a small documented rule table '
          '(`pipeline/lib/grammar_data.py`, `CASE_RULES`) and returns nothing when no rule fits.',
          '* What a particle does to the meaning, and why the word order is what it is: only labels and sequences exist (Q13).',
          '* Contextual meaning: only the word-level gloss exists (Q01).',
          '* A sentence-level "verbal / nominal" label: the Treebank marks constituents (VS, NS, ...) but not the sentence type itself.', '',
          '## Adding a question', '',
          '1. Copy any `queries/qNN_*.py`, give it the next number and fill in `QUESTION`, `KIND`, `LIMITS`, `ARGS`, `DEMO`, `CHECK` and `answer()`.',
          '2. Read only through `queries/_common.py` / `pipeline/lib/grammar_data.py` (the two JSON layers). If the field you need is missing, '
          'the JSON schema must change, not the query.',
          '3. Run `python3 queries/_self_test.py`, then `python3 pipeline/06_docs.py` to regenerate this page.', '',
          '## Workflow checkpoint', '',
          'The pipeline is `01_normalize` -> `02_build_json` -> `03_validate_json` -> `04_generate_csv` -> `05_analysis` -> `06_docs`. After stage 03 the JSON is '
          'final: **decide the questions you need answered at that point**, add or adjust scripts in `queries/`, and only then rely on the CSV and '
          'analysis stages.', '']
    return '\n'.join(L)


def examples():
    out = os.path.join(ROOT, 'docs', 'examples')
    os.makedirs(out, exist_ok=True)
    for f in glob.glob(os.path.join(out, '*.json')):
        os.remove(f)
    W, S = G.words(), G.sentences()
    meta = G.load()[0]['metadata']['word_alignment']

    def dump(name, obj):
        with open(os.path.join(out, name), 'w', encoding='utf-8') as f:
            json.dump(obj, f, ensure_ascii=False, indent=1)
    dump('ayah-67-15.json', {'note': 'Word records 67:15:1-6 and their sentence (10846).',
                             'words': {k: W[k] for k in ['67:15:%d' % i for i in range(1, 7)]}, 'sentence': S['10846']})
    dump('word-merged-treebank-word.json', {
        'note': 'ONE example (of 3; complete list: output/analysis/source-lists/words-merged-in-treebank.csv). The Treebank writes the single word '
                'baEdamaA at 2:181:3; the IndoPak WBW text writes two words (2:181:3, 2:181:4). Its two segments are distributed over them, and every later '
                'Treebank word number in the ayah is one lower than the WBW word number (see segment locations of 2:181:14).',
        'alignment_record': next(m for m in meta['merged_treebank_words'] if m['treebank_word'] == '2:181:3'),
        'words': {k: W[k] for k in ['2:181:3', '2:181:4', '2:181:14']}})
    dump('word-split-across-sentences.json', {
        'note': 'ONE example (of 41; complete list: output/analysis/source-lists/words-split-across-sentences.csv). The prefixes of 9:100:1 are annotated '
                'in sentence 3944 and its stem in 3945. The word is assigned to 3945; sentence 3944 is a prefix-only fragment (1 of 26).',
        'word': W['9:100:1'], 'sentence_3944_fragment': S['3944']})
    small = min((s for s in S.values() if s['span']['crosses_ayah'] and len(s['nodes']) < 40), key=lambda s: len(s['nodes']))
    dump('sentence-crossing-ayah.json', {
        'note': 'ONE example (of 836; complete list: output/analysis/source-lists/sentences-crossing-ayah.csv).', 'sentence': small})
    print('wrote docs/examples/ (4 files)')


def main():
    qs = load_queries()
    with open(os.path.join(ROOT, 'docs', 'QUESTIONS.md'), 'w', encoding='utf-8') as f:
        f.write(questions_md(qs))
    print('wrote docs/QUESTIONS.md (%d questions)' % len(qs))
    examples()


if __name__ == '__main__':
    main()
